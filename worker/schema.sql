CREATE TABLE IF NOT EXISTS results (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL, key TEXT NOT NULL, day TEXT NOT NULL, game TEXT NOT NULL,
  mode TEXT NOT NULL, tries INTEGER NOT NULL, won INTEGER NOT NULL, ms INTEGER NOT NULL DEFAULT 0,
  ip TEXT, at INTEGER NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS results_daily ON results(key, day, game) WHERE mode = 'daily';
CREATE INDEX IF NOT EXISTS results_day ON results(day);
CREATE INDEX IF NOT EXISTS results_key ON results(key);
CREATE INDEX IF NOT EXISTS results_ip_at ON results(ip, at);
CREATE TABLE IF NOT EXISTS answered (key TEXT NOT NULL, day TEXT NOT NULL, answer TEXT NOT NULL, PRIMARY KEY (key, day));
CREATE TABLE IF NOT EXISTS answers (day TEXT NOT NULL, answer TEXT NOT NULL, n INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (day, answer));
