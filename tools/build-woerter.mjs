// Builds data/woerter.js: VALID (all accepted guesses) and ANSWERS (common words, curated).
// Sources (cached 5-letter subsets in tools/cache): enz/german-wordlist (CC0) -> valid-5.txt,
// YNodd/Wortliste_deutsch (CC0, LOD.lu lemmas) intersected with it -> answers-5.txt.
import fs from 'node:fs';
const read = f => fs.readFileSync(new URL('./cache/' + f, import.meta.url), 'utf8').split('\n').filter(Boolean);
// vulgar, obscure, nationalities, old spellings (ss for ß), function-word forms
const DROP = new Set(`ARSCH FOTZE PENIS PISSE NUTTE PORNO TUSSI TITTE KOTZE HUREN HODEN KACKA LESBE NEGER EBOLA
ADDEN ASTAT BISAM BLOCH BOHLE BRITE BRÜSK CHOKE CONGA DAUNE DINGS DOCHT DOHLE DRAIN DÄNIN ERIKA ESTIN FAKEN FESCH FITIS
FRANC FRIES FUDER GAMAY GEÄST GAUDI GETTO GETUE GRIPS HINDU IGITT ILTIS INDER KALBE KAPER KEHLE KIEPE KNUTT KOLIK KORAN
KUHLE KÜFER LAOTE LASUR LETTE LIKEN LODGE MITRA NABEL OCKER OHEIM PATIN PAUKE PEGEL PIROL POLIN POPEL PORÖS PRIEM PUPEN
RECTO REMIS ROTTE RUBEL SAITE SCHIA SEICH SELEN SERBE SPRIT SWASI SYRER THORA TIMEN TRIEL TRÖTE UNGAR UROMA UROPA VERSO
ZARGE ZARIN ZIRKA ZÄSUR TÜRKE RUSSE FINNE ASIAT AFTER ARGON ANTIK ABTUN SCHON
BLOSS GROSS GRUSS WEISS STOSS SPASS FRASS
ALLEM ALLER ALLZU DEINE DENEN EINEM EINER EINES EUREM EURER IHNEN IHREM IHRER JEDEM JEDER JEDES JENEM JENEN JENER JENES
KEINE MEINE SEINE UNSER INDEM DAVOR DAHIN DARUM DABEI DANKE ÄLTER HÖHER`.split(/\s+/));
const valid = [...new Set(read('valid-5.txt'))].sort();
const answers = read('answers-5.txt').filter(w => !DROP.has(w) && valid.includes(w)).sort();
const out = `// generated by tools/build-woerter.mjs, do not edit
export const VALID = '${valid.join(' ')}'.split(' ');
export const ANSWERS = '${answers.join(' ')}'.split(' ');
`;
fs.writeFileSync(new URL('../data/woerter.js', import.meta.url), out);
console.log('valid', valid.length, 'answers', answers.length);
