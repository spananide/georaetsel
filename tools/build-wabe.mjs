// Builds data/wabe.js: ~365 "Wabe" (spelling bee) puzzles from the CC0 lists in tools/cache
// (enz.txt = enz/german-wordlist, yn.csv = YNodd/Wortliste_deutsch). Not committed: the big source lists.
import fs from 'node:fs';
import { mulberry32 } from '../georaetsel/game.js';
const read = f => fs.readFileSync(new URL('./cache/' + f, import.meta.url), 'utf8').split(/\r?\n/);
const ok = /^[A-ZÄÖÜ]{4,12}$/;
const enz = [...new Set(read('enz.txt').map(w => w.trim().toUpperCase()).filter(w => ok.test(w)))];
const common = new Set(read('yn.csv').map(w => w.replace(/,$/, '').trim().toUpperCase()).filter(w => ok.test(w)));
const sets = new Set();
for (const w of common) {
  const s = [...new Set(w)];
  if (s.length === 7 && s.filter(c => 'AEIOUÄÖÜ'.includes(c)).length >= 2) sets.add(s.sort().join(''));
}
const enzSet = new Set(enz);
const puzzles = [];
for (const letters of sets) {
  const L = new Set(letters);
  const words = enz.filter(w => [...w].every(c => L.has(c)));
  const pangrams = words.filter(w => new Set(w).size === 7);
  if (!pangrams.some(p => common.has(p)) || pangrams.length > 3) continue;
  let best = null;
  for (const c of letters) {
    const list = words.filter(w => w.includes(c));
    const n = list.length;
    if (n < 20 || n > 70) continue;
    if (!best || Math.abs(n - 40) < Math.abs(best.list.length - 40)) best = { c, list };
  }
  if (best) puzzles.push([best.c + letters.replace(best.c, ''), best.list.sort().join(' ')]);
}
const rng = mulberry32(20261110);
for (let i = puzzles.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [puzzles[i], puzzles[j]] = [puzzles[j], puzzles[i]]; }
const out = puzzles.slice(0, 365);
fs.writeFileSync(new URL('../data/wabe.js', import.meta.url),
  `// generated by tools/build-wabe.mjs, do not edit\n// [letters (first = centre letter), valid words]\nexport const PUZZLES = ${JSON.stringify(out)};\n`);
console.log('sets', sets.size, 'candidates', puzzles.length, 'written', out.length);
console.log(out.slice(0, 6).map(p => p[0] + ' (' + p[1].split(' ').length + ')').join(' | '));
